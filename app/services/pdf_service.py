"""Render an OSINT search result into a PDF report (reportlab)."""
from __future__ import annotations

import html
from datetime import UTC, datetime
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.models import Search

_ACCENT = colors.HexColor("#6c5ce7")
_DARK = colors.HexColor("#2d3436")
_LIGHT = colors.HexColor("#dfe6e9")


def _styles():
    styles = getSampleStyleSheet()
    styles.add(
        ParagraphStyle(
            "HubTitle",
            parent=styles["Title"],
            textColor=_ACCENT,
            fontSize=22,
            spaceAfter=4,
        )
    )
    styles.add(
        ParagraphStyle(
            "Meta", parent=styles["Normal"], textColor=_DARK, fontSize=10
        )
    )
    styles.add(
        ParagraphStyle(
            "Section",
            parent=styles["Heading2"],
            textColor=_DARK,
            fontSize=13,
            spaceBefore=12,
            spaceAfter=6,
        )
    )
    return styles


def build_search_pdf(search: Search) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=f"OSINT report - {search.query}",
        author="OSINT Hub",
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )
    styles = _styles()
    story: list = []

    safe_query = html.escape(search.query)
    safe_tools = html.escape(", ".join(search.tool_list) or "—")

    story.append(Paragraph("OSINT Hub — Report", styles["HubTitle"]))
    story.append(
        Paragraph(
            f"Target username: <b>{safe_query}</b>", styles["Meta"]
        )
    )
    created = search.created_at or datetime.now(UTC)
    story.append(
        Paragraph(
            f"Engines: {safe_tools} &nbsp;|&nbsp; "
            f"Accounts found: {search.total_found} &nbsp;|&nbsp; "
            f"Generated: {created:%Y-%m-%d %H:%M UTC}",
            styles["Meta"],
        )
    )
    story.append(Spacer(1, 8))

    if not search.results:
        story.append(
            Paragraph("No accounts were found for this username.", styles["Meta"])
        )
        doc.build(story)
        return buffer.getvalue()

    data = [["#", "Engine", "Site", "URL"]]
    for idx, res in enumerate(search.results, start=1):
        data.append([str(idx), res.tool, res.site_name, res.url])

    table = Table(
        data,
        colWidths=[10 * mm, 24 * mm, 40 * mm, 100 * mm],
        repeatRows=1,
    )
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), _ACCENT),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _LIGHT]),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b2bec3")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 12))
    story.append(
        Paragraph(
            "Generated by OSINT Hub. Use responsibly and only on data you are "
            "authorized to investigate.",
            styles["Meta"],
        )
    )

    doc.build(story)
    return buffer.getvalue()
